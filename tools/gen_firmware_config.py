#!/usr/bin/env python3
"""Generate firmware/fivebar_chess/config.h from config/robot.json.

    python3 tools/gen_firmware_config.py               # write the header
    python3 tools/gen_firmware_config.py --check       # fail if it is stale (CI)
    python3 tools/gen_firmware_config.py --config config/robot_v1.json
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "fivebar_chess" / "config.h"


def render(c: dict, source: str) -> str:
    g, d, m, s, mag, pins = (c["geometry"], c["drive"], c["motion"], c["safety"],
                             c["magnet_servo"], c["pins"])
    steps = d["full_steps_per_rev"] * d["microsteps"] * d["gear_ratio"]
    b = lambda v: "true" if v else "false"
    return f"""// Generated by tools/gen_firmware_config.py from {source}. Do not edit by hand:
// change the JSON and re-run the script so MATLAB, Python and firmware agree.
#pragma once

// geometry [mm]
#define FB_L1                {g['proximal_mm']:.3f}f
#define FB_L2                {g['distal_mm']:.3f}f
#define FB_D                 {g['motor_spacing_mm']:.3f}f

// drive
#define FB_STEPS_PER_REV     {steps:.3f}f   // {d['full_steps_per_rev']} x {d['microsteps']} microsteps x {d['gear_ratio']}:1
#define FB_HOME_LEFT_DEG     {d['home_deg'][0]:.3f}f
#define FB_HOME_RIGHT_DEG    {d['home_deg'][1]:.3f}f
#define FB_INVERT_LEFT       {b(d['invert_left'])}
#define FB_INVERT_RIGHT      {b(d['invert_right'])}

// motion
#define FB_VMAX_MM_S         {m['max_speed_mm_s']:.3f}f
#define FB_ACCEL_MM_S2       {m['accel_mm_s2']:.3f}f
#define FB_SEGMENT_MM        {m['segment_mm']:.3f}f
#define FB_MAGNET_SETTLE_MS  {int(m['magnet_settle_ms'])}

// safety [deg]
#define FB_MIN_TRANS_DEG     {s['min_transmission_deg']:.3f}f
#define FB_MIN_ELBOW_DEG     {s['min_elbow_deg']:.3f}f

// magnet servo
#define FB_SERVO_PIN         {mag['pin']}
#define FB_SERVO_ENGAGED     {mag['engaged_deg']}
#define FB_SERVO_RELEASED    {mag['released_deg']}

// pins
#define FB_PIN_LEFT_STEP     {pins['left_step']}
#define FB_PIN_LEFT_DIR      {pins['left_dir']}
#define FB_PIN_RIGHT_STEP    {pins['right_step']}
#define FB_PIN_RIGHT_DIR     {pins['right_dir']}
#define FB_PIN_ENABLE        {pins['enable']}      // -1 = not wired
#define FB_ENABLE_OFF_HIGH   {b(pins['enable_disables_on_high'])}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=str(ROOT / "config" / "robot.json"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    src = Path(a.config).resolve()
    text = render(json.loads(src.read_text()), src.relative_to(ROOT).as_posix())
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/gen_firmware_config.py")
            return 1
        print("config.h is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
