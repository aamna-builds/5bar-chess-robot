#!/usr/bin/env python3
"""Embed config/robot.json and robot_v1.json into simulation/web/config.js.

    python3 tools/gen_web_config.py           # write
    python3 tools/gen_web_config.py --check   # fail if stale (CI)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "simulation" / "web" / "config.js"


def render() -> str:
    v2 = json.loads((ROOT / "config" / "robot.json").read_text())
    v1 = json.loads((ROOT / "config" / "robot_v1.json").read_text())
    return ("// Generated by tools/gen_web_config.py from config/*.json. Do not edit by hand.\n"
            "const FB_CONFIGS = " + json.dumps({"v2": v2, "v1": v1}, indent=1) + ";\n"
            "if (typeof module !== 'undefined') module.exports = FB_CONFIGS;\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("config.js is up to date" if ok else "config.js is stale; run tools/gen_web_config.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
